<?php
$name = "Nana"; // ім'я користувача
$age = 20; // вік користувача
$is_student = true; // чи є студент (true = так)

echo "Мене звати $name, мені $age років. "; // вивід імені та віку
echo $is_student ? "Я студент." : "Я не студент."; // перевірка: студент чи ні
echo "<br><br>"; // перенос рядка в HTML

$numbers = [1, 2, 3, 4, 5]; // створення масиву
$sum = 0; // змінна для збереження суми

foreach ($numbers as $num) { // перебираємо кожне число
    $sum += $num; // додаємо число до суми
}

echo "Сума чисел: $sum"; // виводимо суму
echo "<br><br>"; // перенос рядка

$user = [ // створюємо масив з ключами
    "name" => "Nana", // ім'я
    "email" => "nana@example.com", // email
    "phone" => "+380123456789" // телефон
];

echo "<ul>"; // відкриваємо список

foreach ($user as $key => $value) { // перебираємо ключ і значення
    echo "<li>$key: $value</li>"; // кожен елемент списку
}
echo "</ul>"; // закриваємо список
echo "<br>"; // перенос рядка

if ($age > 18) { // якщо вік більше 18
    echo "Користувач повнолітній"; // виводимо повідомлення
} else {
    echo "Користувач неповнолітній"; // інше повідомлення
}
echo "<br><br>"; // перенос рядка

$grade = 85; // задаємо оцінку

if ($grade >= 90 && $grade <= 100) { // якщо 90-100
    echo "Відмінно";
} elseif ($grade >= 70) { // якщо 70-89
    echo "Добре";
} elseif ($grade >= 50) { // якщо 50-69
    echo "Задовільно";
} else { // якщо менше 50
    echo "Незадовільно";
}
?>
