<?php
$a = 8;
$b = 15;

if ($a > $b) { // якщо a більше b
    $max = $a; // максимум a
    $min = $b; // мінімум b
} else { // інакше
    $max = $b; // максимум b
    $min = $a; // мінімум a
}
echo "Максимум: $max <br>"; // вивід максимуму
echo "Мінімум: $min <br><br>"; // вивід мінімуму

$numbers = [10, 20, 30, 40, 50]; // створюємо масив
$sum = 0; // змінна для суми
$count = count($numbers); // кількість елементів

foreach ($numbers as $num) { // перебираємо масив
    $sum += $num; // додаємо кожне число
}
$average = $sum / $count; // обчислюємо середнє
echo "Середнє арифметичне: $average <br><br>";

$students = [ // створюємо масив
    "Іван Петренко" => 75, // студент і бал
    "Марія Іваненко" => 90,
    "Олег Сидоренко" => 85
];

foreach ($students as $name => $score) { // перебираємо
    if ($score > 80) { // перевірка балу
        echo "$name: $score <br>";
    }
}
echo "<br>";

$num = 12;
if ($num % 3 == 0) { // якщо ділиться на 3
    echo "Число кратне 3 <br>";
}

if ($num % 5 == 0) { // якщо ділиться на 5
    echo "Число кратне 5 <br>";
}
if ($num % 3 != 0 && $num % 5 != 0) { // якщо ні 3, ні 5
    echo "Число не кратне ні 3, ні 5 <br>";
}
echo "<br>";

for ($i = 1; $i <= 10; $i++) { // цикл від 1 до 10
    $result = 7 * $i; // множимо 7 на i
    echo "7 x $i = $result <br>";
}
?>
